"""Did `crewai train` help? (spec §17.2, M8d). Live, Haiku: about $0.03.

    uv run python scripts/compare_trained.py runs/training/short_update.pkl

Runs the ShortUpdateCrew on week 3's published signals twice, without and with the trained file, and scores
both briefs with the M8c judges (faithfulness and quality, 3 samples each) and the deterministic checks.
Writes docs/training.md, including the suggestions training produced.
"""

from __future__ import annotations

import os
import pickle
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # `evals` is a top-level package, not installed

from compintel.runtime import bootstrap  # noqa: E402

WEEK = 3


def main(trained_file: str) -> None:
    bootstrap()
    from crewai.events.event_bus import crewai_event_bus

    from compintel.config import LONG_OUTPUT_MAX_TOKENS, PROJECT_ROOT, make_llm
    from compintel.cost import get_ledger
    from compintel.crews import short_update
    from evals import faithfulness, quality
    from evals.data import WeekRun, load_weeks

    os.chdir(PROJECT_ROOT)
    trained = pickle.loads(Path(trained_file).read_bytes())
    ledger = get_ledger()
    before = ledger.spent_usd
    weeks = load_weeks((1, 2, WEEK))
    known = {i: s for w in weeks for i, s in w.signals.items()}
    reports = weeks[-1].reports
    judge = make_llm(max_tokens=LONG_OUTPUT_MAX_TOKENS)
    context = faithfulness.our_facts()

    rows = {}
    for label, file in (("untrained", None), ("trained", trained_file)):
        print(f"{label}: ShortUpdateCrew on week {WEEK}")
        result = short_update.run(WEEK, reports, trained_agents_file=file)
        crewai_event_bus.flush()
        run = WeekRun(WEEK, label, reports, result.brief, "routine")
        faith = faithfulness.judge_week(run, known, judge, samples=3, context=context)
        qual = quality.judge_week(run, judge, samples=3)
        ids = faithfulness.week_ids(run, known)
        rows[label] = {
            "markdown": result.markdown,
            "words": len(result.markdown.split()),
            "faith": round(100 * faith["points"] / faith["judged"], 1) if faith["judged"] else None,
            "flagged": [v for v in faith["verdicts"] if v["score"] < 1],
            "quality": qual,
            "ids": f"{ids['ids_valid']}/{ids['ids_cited']}",
            "checks": quality.week_checks(run),
        }
    spent = ledger.spent_usd - before

    lines = [
        "# Training the ShortUpdateCrew with `crewai train`",
        "",
        f"Generated by `uv run python scripts/compare_trained.py {trained_file}` (spec §17.2, M8d). "
        f"Week {WEEK}'s published signals, Haiku 5.5, the same crew run twice; judges Haiku x3 (M8c). "
        f"Cost ${spent:.4f}.",
        "",
        "**How training works** (crewai 1.15.33): `crewai train -n 2 -f FILE` runs the crew twice with "
        "`human_input` on every task; after each task the agent gets feedback and redoes it; then each "
        "agent's own LLM turns its feedback into suggestions, saved by role. The feedback came from "
        "`evals/training_feedback.json` (drawn from the M8c eval report) through crewai's human-input "
        "provider hook, not typed. A run given the file appends the suggestions to every prompt of that "
        "role.",
        "",
        "## What training produced",
        "",
    ]
    for role, data in trained.items():
        lines.append(f"**{role}** (training quality {data.get('quality')}):")
        lines += [f"- {s}" for s in data.get("suggestions", [])]
        lines.append("")
    lines += [
        "## Untrained vs trained (week 3)",
        "",
        "| | untrained | trained |",
        "|---|---:|---:|",
        f"| Faithfulness (judge) | {rows['untrained']['faith']} | {rows['trained']['faith']} |",
        f"| Quality mean (1-5) | {rows['untrained']['quality']['mean']} | "
        f"{rows['trained']['quality']['mean']} |",
    ]
    for c in quality.CRITERIA:
        lines.append(f"| - {c} | {rows['untrained']['quality'][c]} | {rows['trained']['quality'][c]} |")
    lines += [
        f"| Words | {rows['untrained']['words']} | {rows['trained']['words']} |",
        f"| Cited ids valid | {rows['untrained']['ids']} | {rows['trained']['ids']} |",
        f"| Threat levels vs ground truth | {rows['untrained']['checks']['threat_levels_match']}/3 | "
        f"{rows['trained']['checks']['threat_levels_match']}/3 |",
        "",
        "One run each: the briefs vary from run to run, so a difference here is a hint, not a measurement.",
        "",
    ]
    for label in ("untrained", "trained"):
        flagged = rows[label]["flagged"]
        lines.append(f"**Claims the judge flagged ({label})**: " + ("none" if not flagged else ""))
        lines += [f"- {v['score']:.2f} ({v['section']}): {v['claim'][:110]} → {v['reason']}" for v in flagged]
        lines.append("")
    for label in ("untrained", "trained"):
        lines += [
            f"<details><summary>The {label} brief</summary>",
            "",
            rows[label]["markdown"],
            "",
            "</details>",
            "",
        ]
    doc = PROJECT_ROOT / "docs" / "training.md"
    doc.write_text("\n".join(lines))
    print(f"wrote {doc}")
    for label in ("untrained", "trained"):
        r = rows[label]
        print(f"{label:9} faithfulness {r['faith']}  quality {r['quality']['mean']}  words {r['words']}")
    print(f"cost ${spent:.4f}   P3 total ${ledger.spent_usd:.4f}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: uv run python scripts/compare_trained.py runs/training/short_update.pkl")
    main(sys.argv[1])
