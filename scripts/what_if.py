"""Checkpoint what-if (spec §13, M8d): fork a finished run with one task's output edited, re-run what follows,
and compare the two briefs. Writes docs/what-if.md. Live, Haiku: about $0.01.

    uv run python scripts/what_if.py

1. Run the ShortUpdateCrew on week 2's published signals (it checkpoints after every task; the DeepDiveCrew,
   which owns `pricing_analysis` in the spec's example, can't checkpoint in crewai 1.15.33: decisions #59).
2. Take the snapshot after `classify_signals` and fork it with StockSathi's analysis rewritten: "the Pro cut
   was 50%, to ₹499" (the signals still say 30%, ₹699). The same edit the `crewai checkpoint` TUI's Fork
   makes (short_update.fork).
3. The writer and renderer run again on the fork; the analyst doesn't. Does the brief follow the edited
   analysis or the evidence?
"""

from __future__ import annotations

import difflib
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # `evals` is a top-level package, not installed

from compintel.runtime import bootstrap  # noqa: E402

WEEK = 2
EDIT = (
    "WHAT-IF: StockSathi cut Pro by 50%, to ₹499 per month [StockSathi-2-1], well below our ₹649 floor; "
    "with UPI Udhaar included it is the most urgent pricing threat to Kolkata."
)


def mentions(text: str) -> dict[str, int]:
    return {p: len(re.findall(re.escape(p), text)) for p in ("50%", "₹499", "30%", "₹699", "floor")}


def main() -> None:
    bootstrap()
    from crewai.events.event_bus import crewai_event_bus

    from compintel.config import PROJECT_ROOT
    from compintel.cost import get_ledger
    from compintel.crews import short_update
    from compintel.listeners import GuardrailLog
    from compintel.models import ThreatAssessments
    from evals.data import load_weeks

    os.chdir(PROJECT_ROOT)  # crewai's output paths and the previous brief are cwd-relative
    ledger = get_ledger()
    before = ledger.spent_usd
    [week] = load_weeks((WEEK,))

    print(f"1/2 original run: ShortUpdateCrew on week {WEEK}'s published signals")
    start = short_update.last_rowid()
    log_a = GuardrailLog()
    original = short_update.run(WEEK, week.reports)
    crewai_event_bus.flush()
    snaps = short_update.snapshots_since(start)
    if len(snaps) < 3:
        raise SystemExit(f"expected a snapshot per task, got {len(snaps)}: was the checkpoint written?")
    after_classify = snaps[0][1]

    threats = original.threats.model_copy(deep=True)
    stock = next(t for t in threats.threats if t.company == "StockSathi")
    edited_from = f"{stock.threat}: {stock.rationale}"
    stock.threat, stock.rationale = "high", EDIT
    stock.signal_ids = sorted({*stock.signal_ids, "StockSathi-2-1"})
    edited = ThreatAssessments.model_validate(threats.model_dump()).model_dump_json()

    print(f"2/2 fork from {after_classify.split('#')[-1]} with StockSathi's analysis edited")
    log_b = GuardrailLog()
    forked = short_update.fork(after_classify, {"classify_signals": edited})
    crewai_event_bus.flush()

    a, b = original.markdown, forked.markdown
    diff = "\n".join(
        difflib.unified_diff(a.splitlines(), b.splitlines(), "original", "what-if", lineterm="", n=1)
    )
    ma, mb = mentions(a), mentions(b)

    def guard(log: GuardrailLog) -> str:
        failed = [e for e in log.entries if not e["passed"]]
        return f"{len(log.entries)} checks, {len(failed)} failed" + (
            ": " + "; ".join(f"{e['name'][:40]} ({(e['error'] or '')[:120]})" for e in failed)
            if failed
            else ""
        )

    spent = ledger.spent_usd - before
    threat_a, threat_b = _threat(original.brief, "StockSathi"), _threat(forked.brief, "StockSathi")
    doc = PROJECT_ROOT / "docs" / "what-if.md"
    doc.write_text(
        f"""# Checkpoint what-if: "what if StockSathi's cut had been 50%?"

Generated by `uv run python scripts/what_if.py` (spec §13, M8d). Week {WEEK}'s published signals, the
ShortUpdateCrew on Haiku 5.5; cost ${spent:.4f}.

**How.** The original run wrote a checkpoint after each task. The fork restores the one after
`classify_signals` (`Crew.fork`, a new branch: the original stays as it was), replaces that task's output, and
kicks off: the analyst doesn't run again; the writer and the renderer do, reading the edit. This is the
`crewai checkpoint` TUI's Fork with its output editor, done from code (`short_update.fork`, which uses
crewai's own `_apply_task_overrides`).

**The edit** (StockSathi, in the analyst's threat assessment):

- original: {edited_from}
- what-if: high: {EDIT}

The signals the writer also reads were not edited: StockSathi-2-1 still says the cut was 30%, to ₹699.

## Did the brief follow the analysis or the evidence?

| mentions | original | what-if |
|---|---:|---:|
"""
        + "\n".join(f"| `{k}` | {ma[k]} | {mb[k]} |" for k in ma)
        + f"""

| | original | what-if |
|---|---|---|
| Headline | {original.brief.headline} | {forked.brief.headline} |
| StockSathi threat (brief) | {threat_a} | {threat_b} |
| Guardrails | {guard(log_a)} | {guard(log_b)} |

## Diff (rendered briefs)

```diff
{diff}
```
"""
    )
    print(f"wrote {doc}   mentions original {ma}  what-if {mb}")
    print(f"cost ${spent:.4f}   P3 total ${ledger.spent_usd:.4f}")


def _threat(brief, company: str) -> str:
    return next((f"{t.threat}: {t.rationale[:90]}" for t in brief.threats if t.company == company), "-")


if __name__ == "__main__":
    main()
