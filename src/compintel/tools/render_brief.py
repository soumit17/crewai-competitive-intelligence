"""RenderBriefTool (spec §6): `BaseTool` with `result_as_answer=True`.

`result_as_answer` makes the tool's return value the task's final output verbatim: crewai stops the agent loop
right after the tool runs, so no LLM rewrites or "summarises" the markdown. The rendering is deterministic
code from the approved Brief (saved by the write task's callback), not prose generated by the model.
"""

from __future__ import annotations

from pathlib import Path

from crewai.tools import BaseTool
from pydantic import BaseModel, Field

from compintel.models import Brief

DRAFTS_DIR = Path("briefs") / "drafts"  # cwd-relative, like crewai's output_file (see crews/short_update)


def draft_path(week: int, suffix: str = ".json") -> Path:
    return DRAFTS_DIR / f"week-{week:02d}{suffix}"


def render_markdown(brief: Brief) -> str:
    def bullets(items: list[str]) -> str:
        return "\n".join(f"- {i}" for i in items) if items else "- None."

    threats = "\n".join(
        f"| {t.company} | **{t.threat}** | {t.rationale} |"
        for t in sorted(brief.threats, key=lambda t: t.company)
    )
    recs = "\n".join(
        f"| {r.action} | {r.owner} | {r.urgency.replace('_', ' ')} | {', '.join(r.signal_ids)} |"
        for r in brief.recommendations
    )
    return f"""# Week {brief.week:02d}: {brief.headline}

*Route: {brief.route}*

## TL;DR
{bullets(brief.tl_dr)}

## Since last week
{bullets(brief.since_last_week)}

## Threats
| Competitor | Threat | Why |
|---|---|---|
{threats}

## Recommendations
| Action | Owner | Urgency | Signals |
|---|---|---|---|
{recs}

## Watchlist
{bullets(brief.watchlist)}

## Discounted claims
{bullets(brief.discounted_claims)}
"""


class RenderBriefArgs(BaseModel):
    week: int = Field(ge=1, description="The week whose approved brief to render.")


class RenderBriefTool(BaseTool):
    name: str = "render_brief"
    description: str = (
        "Render the approved brief for a week as the final markdown document. Its output is returned as your "
        "answer unchanged, so call it once and stop."
    )
    args_schema: type[BaseModel] = RenderBriefArgs
    result_as_answer: bool = True

    def _run(self, week: int) -> str:
        path = draft_path(week)
        if not path.exists():
            return f"Error: no approved brief for week {week} at {path}."
        return render_markdown(Brief.model_validate_json(path.read_text()))
