"""One table of 0-100 metrics for all three weeks, the baseline, the regression gate and the M8 acceptance.

Gate (spec §17.1): a metric more than 3 points below `evals/baseline.json` fails. Metrics a run didn't
measure (judges off) are skipped, never counted as a drop.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from typing import Any

from compintel.config import PROJECT_ROOT, get_settings
from evals import compare, faithfulness, quality, signals
from evals.data import WeekRun

BASELINE = PROJECT_ROOT / "evals" / "baseline.json"
REPORT = PROJECT_ROOT / "evals" / "report.md"
TOLERANCE = 3.0
# Spec M8 acceptance: week-2 material recall = 100%; rumor never claimed; faithfulness >= 95%.
ACCEPTANCE = {
    "signals.week2_material_recall": 100.0,
    "rumor.never_claimed": 100.0,
    "faithfulness.judge": 95.0,
}


def evaluate(runs: list[WeekRun], faith_llm: Any = None, quality_llm: Any = None) -> dict:
    known = {}
    per_week: dict[int, dict] = {}
    for run in sorted(runs, key=lambda r: r.week):
        known.update(run.signals)  # this week's and every earlier week's signals
        per_week[run.week] = {
            "state_id": run.state_id,
            "signals": signals.week_scores(run),
            "ids": faithfulness.week_ids(run, dict(known)),
            "rumor": faithfulness.week_rumor(run),
            "checks": quality.week_checks(run),
        }
        if faith_llm is not None:
            per_week[run.week]["faithfulness_judge"] = faithfulness.judge_week(run, dict(known), faith_llm)
        if quality_llm is not None:
            per_week[run.week]["quality_judge"] = quality.judge_week(run, quality_llm)

    pick = lambda key: {w: d[key] for w, d in per_week.items() if key in d}  # noqa: E731
    scores = {
        **signals.scores(pick("signals")),
        **faithfulness.scores(pick("ids"), pick("rumor"), pick("faithfulness_judge") or None),
        **quality.scores(pick("checks"), pick("quality_judge") or None),
    }
    human = quality.human_scores()
    return {
        "at": datetime.now(UTC).isoformat(timespec="seconds"),
        "weeks": per_week,
        "scores": scores,
        "human": human,
        "agreement": quality.agreement(pick("quality_judge"), human) if quality_llm is not None else None,
    }


# A judged metric is comparable only when the same model judged it both times (Haiku vs Sonnet would show a
# "drop" that is the judge's, not the briefs').
JUDGED = {"faithfulness.judge": "faithfulness", "quality.judge": "quality"}


def comparable(baseline: dict, judges: dict[str, str]) -> dict[str, float | None]:
    """The baseline's scores, minus judged metrics whose judge differs from this run's."""
    before_judges = baseline.get("judges", {})
    return {
        m: v
        for m, v in baseline.get("scores", {}).items()
        if m not in JUDGED or before_judges.get(JUDGED[m]) == judges.get(JUDGED[m])
    }


def regressions(scores: dict[str, float | None], baseline: dict[str, float | None]) -> list[str]:
    out = []
    for metric, before in baseline.items():
        now = scores.get(metric)
        if before is not None and now is not None and now < before - TOLERANCE:
            out.append(f"{metric}: {now} < baseline {before} - {TOLERANCE}")
    return out


def acceptance(scores: dict[str, float | None]) -> list[str]:
    """Unmet M8 acceptance items (an unmeasured one is unmet: the judge has to run)."""
    out = []
    for metric, needed in ACCEPTANCE.items():
        value = scores.get(metric)
        if value is None or value < needed:
            out.append(f"{metric}: {value if value is not None else 'not measured'} (needs >= {needed})")
    return out


def load_baseline() -> dict:
    """{"at", "judges", "scores"}, or {} before the first --save-baseline."""
    return json.loads(BASELINE.read_text()) if BASELINE.exists() else {}


def save_baseline(result: dict, judges: dict[str, str]) -> None:
    BASELINE.write_text(
        json.dumps({"at": result["at"], "judges": judges, "scores": result["scores"]}, indent=2) + "\n"
    )


def save_run(result: dict) -> str:
    path = get_settings().p3_runs_dir / "evals" / f"{result['at'].replace(':', '')}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, indent=2, ensure_ascii=False, default=str))
    return str(path)


def markdown(result: dict, judges: dict[str, str], baseline: dict[str, float | None]) -> str:
    w = []
    w.append(f"# Eval report ({result['at']})\n")
    w.append(
        f"Judges: faithfulness `{judges.get('faithfulness', 'off')}`, "
        f"quality `{judges.get('quality', 'off')}`. "
        "Generated by `uv run python -m evals run`; raw data in `runs/evals/`.\n"
    )
    w.append("| metric | score | baseline |\n|---|---:|---:|")
    for metric, value in result["scores"].items():
        before = baseline.get(metric)
        w.append(f"| {metric} | {'-' if value is None else value} | {'-' if before is None else before} |")
    failing = acceptance(result["scores"])
    w.append("\n**M8 acceptance:** " + ("met." if not failing else "not met: " + "; ".join(failing)))
    for week, d in result["weeks"].items():
        s, ids, r, c = d["signals"], d["ids"], d["rumor"], d["checks"]
        w.append(f"\n## Week {week} (route {s['route']}{'' if s['route_ok'] else ', expected otherwise'})\n")
        w.append(
            f"- Expected signals found: {s['found']}/{s['expected']}"
            + (f"; missed: {'; '.join(s['missed'])}" if s["missed"] else "")
        )
        w.append(
            f"- High-impact signals: {s['high']}, of which key: {s['high_key']}"
            + (f"; others: {'; '.join(s['high_extra'][:4])}" if s["high_extra"] else "")
        )
        w.append(
            f"- Cited ids valid: {ids['ids_valid']}/{ids['ids_cited']}"
            + (f"; unknown: {', '.join(ids['unknown_ids'])}" if ids["unknown_ids"] else "")
            + f"; claims citing: {ids['claims_citing']}/{ids['claims_must_cite']}"
        )
        w.append(
            f"- Rumor claimed: {'YES' if r['claims_rumor'] else 'no'}; "
            f"discounted: {r['discounted']}/{r['must_discount']}"
        )
        w.append(f"- Threat levels: {', '.join(f'{k} {v}' for k, v in c['threat_levels'].items())}")
        if fj := d.get("faithfulness_judge"):
            bad = [v for v in fj["verdicts"] if v["verdict"] != "supported"]
            w.append(f"- Faithfulness judge: {fj['judged']} claims, {len(bad)} not fully supported")
            w.extend(f"  - {v['verdict']} ({v['section']}): {v['claim'][:90]} → {v['reason']}" for v in bad)
        if qj := d.get("quality_judge"):
            w.append(
                "- Quality judge: "
                + ", ".join(f"{k} {qj[k]}" for k in quality.CRITERIA)
                + f" (mean {qj['mean']}): {qj['comment']}"
            )
        if (h := result["human"].get(int(week))) is not None:
            w.append("- Your scores: " + ", ".join(f"{k} {h[k]}" for k in quality.CRITERIA))
    if result.get("agreement"):
        a = result["agreement"]
        w.append(
            f"\n**Judge vs you:** mean absolute difference {a['mean_abs_diff']} over {a['pairs']} scores."
        )
    w.append("\n## Process comparison (M4, week 2, one live run each)\n")
    w.append(compare.table())
    return "\n".join(w) + "\n"
